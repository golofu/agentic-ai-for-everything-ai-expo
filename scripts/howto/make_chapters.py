"""Build cover/assets/videos/howto-chapters.js: clickable step lists for the how-to clips.
python -I scripts/howto/make_chapters.py
Start times are computed from the same cut specs edit.py used (segment length / speed, summed),
so a chapter starts exactly where its part of the clip starts.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
REC = pathlib.Path(r"C:\Users\User\AppData\Local\Temp\claude\785b8701d42b026f\8724ba23-8dc5-42db-aebc-2ec74bc49f15\scratchpad\rec")
VIDEOS = ROOT / "cover/assets/videos"

# caption prefix -> step label (first match wins); captions come from make_spec.py
KINDS = [
    ("ไฟล์ตั้งต้น", "ไฟล์ตั้งต้น"), ("เปิดโฟลเดอร์", "ไฟล์ตั้งต้น"),
    ("Claude Desktop: ", "เลือกโฟลเดอร์"),
    ("วางคำสั่ง", "วางคำสั่ง"),
    ("Claude เปิดไฟล์และลงมือทำเอง", "Claude ลงมือทำ"),
    ("Claude เสนอแผนก่อน", "Claude เสนอแผน"),
    ("พิมพ์ ", "พิมพ์ ตกลง"),
    ("Claude จัดไฟล์ตามแผน", "Claude จัดไฟล์"),
    ("อ่านคำตอบ", "อ่านคำตอบ"),
    ("ไฟล์ใหม่มารออยู่", "ไฟล์ใหม่"), ("ไม่มีไฟล์ใหม่", "ผลลัพธ์"),
    ("เปิดไฟล์ดูผลงาน", "เปิดดูผลงาน"), ("เปิด ", "เปิดดูผลงาน"),
]
WORKSPACE = ["เปิด Claude Desktop", "เลือกโฟลเดอร์ว่าง", "กด Allow", "วาง Prompt", "Allow อีกครั้ง", "ตอบคำถาม 3 รอบ", "ได้ Workspace 7 ไฟล์"]


def plain(cap):
    return re.sub(r"<[^>]+>", "", cap)


def label_of(cap):
    c = plain(cap)
    for prefix, lab in KINDS:
        if c.startswith(prefix):
            return lab
    return c[:18]


def chapters_from(segs, labels=None):
    out, t = [], 0.0
    for i, s in enumerate(segs):
        lab = labels[i] if labels else label_of(s.get("cap", ""))
        if not out or out[-1]["label"] != lab:
            out.append({"t": round(t, 1), "label": lab})
        t += (s["out"] - s["in"]) / s.get("speed", 1)
    return out


data = {}
for spec_f in sorted(list(REC.glob("*.spec.json")) + [REC / "setup-workspace.json"]):
    slug = spec_f.name.split(".")[0]
    if not (VIDEOS / f"howto-{slug}.mp4").exists():
        continue
    spec = json.loads(spec_f.read_text(encoding="utf-8-sig"))
    if slug == "setup-workspace":
        ch = chapters_from(spec["segments"], WORKSPACE)
    else:
        ch = chapters_from(spec["segments"])
        tail = REC / f"{slug}.tail.json"
        if tail.exists():
            spec = json.loads((REC / f"{slug}.base.json").read_text(encoding="utf-8-sig"))
            ch = chapters_from(spec["segments"])  # fix_open.py: base clip (spec without the ending) + re-recorded ending
            base_len = sum((s["out"] - s["in"]) / s.get("speed", 1) for s in spec["segments"])
            ch.append({"t": round(base_len, 1), "label": "เปิดดูผลงาน"})
    data[f"howto-{slug}"] = ch

js = "// Generated by scripts/howto/make_chapters.py — step lists beside the how-to clips (seconds from clip start)\n"
js += "window.howtoChapters = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
(VIDEOS / "howto-chapters.js").write_text(js, encoding="utf-8")
print(len(data), "clips;", "portfolio:", data.get("howto-portfolio"))
